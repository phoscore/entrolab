import {readFile,writeFile,mkdir,readdir} from 'node:fs/promises';
import {dirname,join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {gzipSync} from 'node:zlib';
import {ATLAS_RELEASE} from '../cosmic-explorer/atlas-format.mjs';
import {buildAtlas,frozenExport,auditAtlas,atlasSha256} from '../cosmic-explorer/atlas-build.mjs';

const [command,path,...extra]=process.argv.slice(2);
if (extra.length || !((command==='--check' && !path) || (command==='--from' && path))) {
  throw new Error('Usage: node scripts/build-real-sky.mjs --check | --from captured.csv');
}
const dir=fileURLToPath(new URL(`../dist/explorer/data/${ATLAS_RELEASE}/`,import.meta.url));
const codec=await readFile(new URL('../cosmic-explorer/atlas-format.mjs', import.meta.url));
const raw=command==='--from'?await readFile(path):await frozenExport(dir);
const {manifest,files,rows}=await buildAtlas(raw);
const crossCheck=await auditAtlas(rows);
const pin=Buffer.from(`// Generated by scripts/build-real-sky.mjs.\nexport const ATLAS_MANIFEST_SHA256 = '${atlasSha256(files.get('manifest.json'))}';\n`);

async function deliver(path,bytes,{generated=false}={}) {
  let existing;
  try {existing=await readFile(path);} catch (e) {if (e.code!=='ENOENT') throw e;}
  if (existing) {
    if (existing.equals(bytes)) return;
    if (generated && command==='--from') await writeFile(path,bytes);
    else throw new Error(`${generated?'Stale Real Sky artifact':'Immutable Real Sky file mismatch'}: ${path}`);
  } else if (command==='--from') {
    await mkdir(dirname(path),{recursive:true});
    await writeFile(path,bytes,{flag:'wx'});
  } else throw new Error(`Missing Real Sky file: ${path}`);
}
for (const [key,bytes] of files) await deliver(join(dir,key),bytes);
const actualFiles=(await readdir(dir,{recursive:true,withFileTypes:true})).filter(f=>f.isFile()).length;
if (actualFiles!==files.size) throw new Error('Unexpected files in immutable Real Sky release');
await deliver(fileURLToPath(new URL('../dist/explorer/foundation/atlas-format.mjs',import.meta.url)),codec,{generated:true});
await deliver(fileURLToPath(new URL('../dist/explorer/atlas-pin.mjs',import.meta.url)),pin,{generated:true});

const sizes={};
for (const [path,bytes] of files) {
  const group=path.split('/')[0], size=sizes[group]??={files:0,raw:0,gzipEstimate:0,max:0};
  size.files++;size.raw+=bytes.length;
  size.gzipEstimate+=path.endsWith('.gz')?bytes.length:gzipSync(bytes,{level:6}).length;
  size.max=Math.max(size.max,bytes.length);
}
console.log(JSON.stringify({release:manifest.release,manifestSha256:atlasSha256(files.get('manifest.json')),counts:manifest.counts,crossCheck,sizes},null,2));
