import {mkdir,readFile,readdir,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {dirname,join} from 'node:path';
import {DESI_RELEASE} from '../dist/explorer/foundation/desi-format.mjs';
import {buildDeepSky} from '../cosmic-explorer/desi-build.mjs';

const [command,...rest] = process.argv.slice(2);
if (rest.length || !['--build','--check'].includes(command)) throw new Error('Use --build or --check');
const {files,manifest,manifestHash,referenceRows,footprintSquareDegrees} = await buildDeepSky();
const root = fileURLToPath(new URL(`../dist/explorer/data/${DESI_RELEASE}/`,import.meta.url));
const pinPath = new URL('../dist/explorer/desi-pin.mjs',import.meta.url);
const pin = Buffer.from(`// Generated by scripts/build-deep-sky.mjs.\nexport const DESI_MANIFEST_SHA256 = '${manifestHash}';\n`);
for (const [relative,expected] of files) {
  const path = join(root,relative);
  const existing = await readFile(path).catch(error=>{if(error.code !== 'ENOENT') throw error;return null;});
  if (existing) {
    if (!expected.equals(existing)) throw new Error(`Immutable DESI release mismatch: ${relative}`);
  } else {
    if (command === '--check') throw new Error(`Missing DESI payload: ${relative}`);
    await mkdir(dirname(path),{recursive:true});
    await writeFile(path,expected,{flag:'wx'});
  }
}
const disk = await readdir(root,{recursive:true,withFileTypes:true});
if (disk.filter(entry=>entry.isFile()).length !== files.size) throw new Error('Unexpected DESI release file');
if (command === '--build') await writeFile(pinPath,pin);
else if (!(await readFile(pinPath)).equals(pin)) throw new Error('Stale DESI browser pin');
const sizes = {};
for (const [path,bytes] of files) {
  const section = path.split('/')[0];
  const stats = sizes[section]??={files:0,bytes:0,max:0};
  stats.files++;stats.bytes+=bytes.length;stats.max=Math.max(stats.max,bytes.length);
}
console.log(JSON.stringify({release:manifest.release,manifestHash,counts:manifest.counts,referenceRows,
  footprintTiles:manifest.footprint.tiles,footprintSquareDegrees,sizes},null,2));
