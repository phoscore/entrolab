import {mkdir, readFile, writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {join} from 'node:path';
import {buildSample, sampleDir, sha256, writeSample} from '../cosmic-explorer/pipeline.mjs';

const root = fileURLToPath(new URL('../dist/explorer/', import.meta.url));
const check = process.argv.includes('--check');
const sample = await buildSample();
const expected = await readFile(join(sampleDir, 'manifest.json'));
if (!expected.equals(sample.files.get('manifest.json'))) throw new Error('Sample manifest changed');
const files = new Map([...sample.files].map(([p, b]) => [`data/${sample.manifest.release}/${p}`, b]));
for (const name of ['schema.mjs', 'access.mjs', 'tiles.mjs']) {
  files.set(`foundation/${name}`, await readFile(new URL(`../cosmic-explorer/${name}`, import.meta.url)));
}
files.set('release.mjs', Buffer.from(`// Generated by scripts/build-explorer.mjs from the pinned Phase-1 sample.\nexport const RELEASE = '${sample.manifest.release}';\nexport const MANIFEST_SHA256 = '${sha256(expected)}';\n`));
if (check) {
  for (const [p, bytes] of files) {
    if (!(await readFile(join(root, p))).equals(bytes)) throw new Error(`Stale viewer artifact: ${p}`);
  }
} else {
  await writeSample(join(root, 'data'), sample);
  for (const [p, bytes] of files) {
    if (p.startsWith('data/')) continue;
    await mkdir(join(root, p, '..'), {recursive: true});
    await writeFile(join(root, p), bytes);
  }
}
console.log(`${check ? 'Verified' : 'Prepared'} ${files.size} Explorer artifacts; sample schema v${sample.manifest.schemaVersion}; ${sha256(expected)}`);
