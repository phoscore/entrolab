import {mkdir,readFile,readdir,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {dirname,join} from 'node:path';
import {buildNeighborhood} from '../cosmic-explorer/neighborhood-build.mjs';

const [option,...extra]=process.argv.slice(2);
if (extra.length || !['--check','--build'].includes(option)) throw new Error('Use --check or --build');
const {manifest,manifestHash,files,checks}=await buildNeighborhood();
const root=fileURLToPath(new URL(`../dist/explorer/data/${manifest.release}/`,import.meta.url));
const pinPath=new URL('../dist/explorer/neighborhood-pin.mjs',import.meta.url);
const pin=Buffer.from(`// Generated by scripts/build-neighborhood.mjs.\nexport const NEIGHBORHOOD_MANIFEST_SHA256 = '${manifestHash}';\n`);
for (const [name,bytes] of files) {
  const path=join(root,name);
  const existing=await readFile(path).catch(error=>{if (error.code!=='ENOENT') throw error;return null;});
  if(existing) {
    if(!existing.equals(bytes)) throw new Error(`Immutable neighborhood release differs: ${name}`);
  } else {
    if(option==='--check') throw new Error(`Neighborhood payload missing: ${name}`);
    await mkdir(dirname(path),{recursive:true});
    await writeFile(path,bytes,{flag:'wx'});
  }
}
const actual=(await readdir(root,{withFileTypes:true,recursive:true})).filter(entry=>entry.isFile());
if(actual.length!==files.size) throw new Error('Unexpected file in immutable neighborhood release');
if(option==='--build') await writeFile(pinPath,pin);
else if(!(await readFile(pinPath)).equals(pin)) throw new Error('Stale neighborhood browser pin');
console.log(JSON.stringify({release:manifest.release,count:manifest.count,manifestHash,checks,files:files.size,
  bytes:[...files.values()].reduce((n,bytes)=>n+bytes.length,0),
  overviewBytes:files.get('manifest.json').length+files.get('positions.bin').length,
  largestDetail:Math.max(...[...files].filter(([p])=>p.startsWith('details/')).map(([,b])=>b.length))},null,2));
